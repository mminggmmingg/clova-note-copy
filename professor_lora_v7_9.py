#!/usr/bin/env python3
"""Local Clova V7.9.2 professor-adaptive BatiSay LoRA trainer.

This process is intentionally separate from the Flask runtime.  The runtime
collects human-corrected audio/text pairs; this trainer consumes the pool,
measures the currently-active model on a fixed hold-out set, fine-tunes only
LoRA weights, measures the candidate again, and promotes it only when CER does
not regress.
"""

import argparse
import gc
import hashlib
import json
import math
import os
import random
import re
import shutil
import time
import unicodedata
import wave
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import torch
from torch.utils.data import DataLoader, Dataset
from transformers import AutoModelForSpeechSeq2Seq, AutoProcessor

# V7.9.2 gfx1151 / ROCm training path (inherits V7.9.1 MIOpen hotfix):
# PyTorch exposes AMD MIOpen convolution kernels through the cudnn backend.
# This machine already needs cudnn disabled for BatiSay/Qwen inference; the
# LoRA trainer is a separate subprocess, so it must apply the same workaround
# explicitly or Whisper encoder Conv1d can raise miopenStatusUnknownError.
torch.backends.cudnn.enabled = False
try:
    torch.backends.cudnn.benchmark = False
except Exception:
    pass

SR = 16000


def now_iso():
    from datetime import datetime
    return datetime.now().astimezone().isoformat()


def read_json(path, default):
    try:
        return json.loads(Path(path).read_text(encoding="utf-8"))
    except Exception:
        return default


def write_json(path, data):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    tmp.replace(path)


def update_status(path, **fields):
    old = read_json(path, {})
    old.update(fields)
    old["updated_at"] = now_iso()
    write_json(path, old)


def load_wav_mono_16k(path):
    with wave.open(str(path), "rb") as wf:
        channels = wf.getnchannels()
        width = wf.getsampwidth()
        rate = wf.getframerate()
        frames = wf.readframes(wf.getnframes())
    if width != 2:
        raise ValueError(f"expected PCM16 WAV, got sample_width={width}: {path}")
    audio = np.frombuffer(frames, dtype=np.int16).astype(np.float32) / 32768.0
    if channels > 1:
        audio = audio.reshape(-1, channels).mean(axis=1)
    if rate != SR:
        # Training pool is generated by Local Clova and should always be 16 kHz.
        raise ValueError(f"expected {SR}Hz training WAV, got {rate}: {path}")
    return audio


def norm_for_metric(text):
    text = unicodedata.normalize("NFKC", str(text or "")).casefold()
    text = re.sub(r"[^0-9a-z가-힣\s]", " ", text)
    return re.sub(r"\s+", " ", text).strip()


def levenshtein(a, b):
    if len(a) < len(b):
        a, b = b, a
    prev = list(range(len(b) + 1))
    for i, x in enumerate(a, 1):
        cur = [i]
        for j, y in enumerate(b, 1):
            cur.append(min(
                cur[-1] + 1,
                prev[j] + 1,
                prev[j - 1] + (x != y),
            ))
        prev = cur
    return prev[-1]


def error_rates(refs, hyps):
    cer_num = cer_den = 0
    wer_num = wer_den = 0
    for ref, hyp in zip(refs, hyps):
        r = norm_for_metric(ref)
        h = norm_for_metric(hyp)
        rc = list(r.replace(" ", ""))
        hc = list(h.replace(" ", ""))
        rw = r.split()
        hw = h.split()
        cer_num += levenshtein(rc, hc)
        cer_den += max(1, len(rc))
        wer_num += levenshtein(rw, hw)
        wer_den += max(1, len(rw))
    return {
        "cer": cer_num / max(1, cer_den),
        "wer": wer_num / max(1, wer_den),
        "samples": len(refs),
    }


def sample_group_key(item):
    """Keep all derivatives from one corrected SEG in the same split.

    A Human edit can create both an utterance sample and one or more phrase
    crops. Splitting those independently would leak nearly-identical audio
    between train and validation and make CER/WER look better than reality.
    """
    session = str(item.get("source_session") or "")
    segment = str(item.get("source_segment") or "")
    if session and segment:
        return f"{session}:{segment}"
    return str(item.get("id") or item.get("sample_id") or "")


def split_samples(samples, profile):
    """Professor-level fixed hold-out split with no SEG leakage.

    The validation *groups* are chosen on the first training run and persisted
    in profile.json. Future adapter versions never train on those corrected
    SEG groups, so CER/WER remains comparable across versions.
    """
    groups = {}
    for item in samples:
        groups.setdefault(sample_group_key(item), []).append(item)
    keys = sorted(
        groups,
        key=lambda key: int(hashlib.sha1(key.encode("utf-8")).hexdigest()[:12], 16),
    )
    saved = [str(x) for x in (profile.get("validation_group_keys") or []) if str(x) in groups]
    if saved:
        val_keys = set(saved)
    else:
        # Hold out ~20% of corrected SEG groups, at least one and preferably
        # two. Group-level selection prevents phrase/utterance leakage.
        group_n = len(keys)
        val_group_n = max(1, int(round(group_n * 0.20)))
        if group_n >= 6:
            val_group_n = max(2, val_group_n)
        val_group_n = min(val_group_n, max(1, group_n - 2)) if group_n >= 3 else 0
        val_keys = set(keys[:val_group_n])

    # Train can use both full utterances and precise phrase crops. Metrics,
    # however, should represent real segment transcription quality, so each
    # validation SEG contributes only its full Human-corrected utterance. This
    # avoids double-counting the same audio through phrase derivatives and
    # prevents an artificially optimistic CER/WER.
    val = [
        item
        for key in keys if key in val_keys
        for item in groups[key]
        if str(item.get("kind") or "utterance") == "utterance"
    ]
    train = [item for key in keys if key not in val_keys for item in groups[key]]
    return train, val, sorted(val_keys)


class SpeechTextDataset(Dataset):
    def __init__(self, samples, processor):
        self.samples = samples
        self.processor = processor

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, idx):
        item = self.samples[idx]
        audio = load_wav_mono_16k(item["audio_path"])
        feats = self.processor.feature_extractor(
            audio,
            sampling_rate=SR,
            return_tensors="pt",
        ).input_features[0]
        labels = self.processor.tokenizer(
            str(item["target"]),
            return_tensors="pt",
        ).input_ids[0]
        return {
            "input_features": feats,
            "labels": labels,
        }


@dataclass
class Collator:
    processor: object
    decoder_start_token_id: int

    def __call__(self, features):
        inputs = [{"input_features": f["input_features"]} for f in features]
        batch = self.processor.feature_extractor.pad(inputs, return_tensors="pt")
        label_features = [{"input_ids": f["labels"]} for f in features]
        labels_batch = self.processor.tokenizer.pad(label_features, return_tensors="pt")
        labels = labels_batch["input_ids"].masked_fill(labels_batch["attention_mask"].ne(1), -100)
        if labels.shape[1] and torch.all(labels[:, 0] == self.decoder_start_token_id):
            labels = labels[:, 1:]
        batch["labels"] = labels
        return batch


def resolve_pool(prof_root):
    pool = read_json(prof_root / "training_pool.json", {"samples": {}})
    raw = pool.get("samples", {})
    items = list(raw.values()) if isinstance(raw, dict) else list(raw or [])
    usable = []
    for item in items:
        if not isinstance(item, dict) or item.get("disabled"):
            continue
        path = Path(str(item.get("audio_path") or ""))
        target = str(item.get("target") or "").strip()
        dur = float(item.get("duration_sec") or 0.0)
        if not path.is_file() or not target or dur < 0.45 or dur > 30.5:
            continue
        usable.append(item)
    return usable


def select_incremental_train(train_samples, profile):
    previous = set(profile.get("trained_sample_ids") or [])
    new_items = [x for x in train_samples if str(x.get("id")) not in previous]
    if not previous:
        return train_samples, new_items
    old_items = [x for x in train_samples if str(x.get("id")) in previous]
    # New corrections dominate; replay protects older pronunciation patterns.
    replay_n = min(len(old_items), max(4, math.ceil(len(new_items) * 0.35)))
    old_items = sorted(old_items, key=lambda x: str(x.get("id")))
    replay = old_items[:replay_n]
    return new_items + replay, new_items


def load_model(base_model, active_adapter, trainable):
    from peft import LoraConfig, PeftModel, get_peft_model

    dtype = torch.float16 if torch.cuda.is_available() else torch.float32
    model = AutoModelForSpeechSeq2Seq.from_pretrained(
        base_model,
        torch_dtype=dtype,
        low_cpu_mem_usage=True,
    )
    model.config.use_cache = False

    if active_adapter and Path(active_adapter).is_dir():
        model = PeftModel.from_pretrained(
            model,
            active_adapter,
            is_trainable=trainable,
        )
    elif trainable:
        # Whisper is an ASR model whose forward() consumes input_features,
        # not text input_ids.  Follow PEFT's own Whisper example and leave
        # task_type unset so get_peft_model returns the generic PeftModel
        # wrapper instead of the Seq2Seq-LM wrapper.
        cfg = LoraConfig(
            r=8,
            lora_alpha=16,
            lora_dropout=0.05,
            target_modules=["q_proj", "v_proj"],
            bias="none",
        )
        model = get_peft_model(model, cfg)

    if torch.cuda.is_available():
        model.to("cuda:0")
    return model


def predict_samples(model, processor, samples, status_file=None, progress_base=0.0, progress_span=0.1, message="평가 중"):
    refs, hyps = [], []
    model.eval()
    dtype = torch.float16 if torch.cuda.is_available() else torch.float32
    for i, item in enumerate(samples, 1):
        audio = load_wav_mono_16k(item["audio_path"])
        inp = processor.feature_extractor(audio, sampling_rate=SR, return_tensors="pt").input_features
        if torch.cuda.is_available():
            inp = inp.to("cuda:0", dtype=dtype)
        else:
            inp = inp.to(dtype=dtype)
        with torch.inference_mode():
            ids = model.generate(
                inp,
                language="korean",
                task="transcribe",
                max_new_tokens=160,
                num_beams=1,
            )
        hyp = processor.tokenizer.batch_decode(ids, skip_special_tokens=True)[0].strip()
        refs.append(str(item["target"]))
        hyps.append(hyp)
        if status_file:
            frac = i / max(1, len(samples))
            update_status(
                status_file,
                progress=progress_base + progress_span * frac,
                message=f"{message} · {i}/{len(samples)}",
            )
    return error_rates(refs, hyps), refs, hyps


def train(args):
    print(
        "[V7.9.2 TRAIN BACKEND] "
        f"hip={torch.version.hip!r} cuda_available={torch.cuda.is_available()} "
        f"cudnn_enabled={torch.backends.cudnn.enabled}",
        flush=True,
    )
    data_root = Path(args.data_root)
    prof_root = data_root / "professors" / args.professor_id
    status_file = Path(args.status_file or prof_root / "training_status.json")
    profile_path = prof_root / "profile.json"
    profile = read_json(profile_path, {})
    samples = resolve_pool(prof_root)
    correction_groups = {sample_group_key(x) for x in samples}

    update_status(
        status_file,
        status="running",
        stage="prepare",
        stage_label="학습 데이터 준비",
        progress=0.02,
        message=f"Human correction {len(correction_groups)} SEG · {len(samples)} samples 확인 중",
        started_at=now_iso(),
        error=None,
    )

    if len(correction_groups) < args.min_samples:
        raise RuntimeError(
            f"LoRA 학습에는 최소 {args.min_samples}개의 Human-corrected SEG가 필요합니다. "
            f"현재 {len(correction_groups)}개"
        )

    train_all, val_samples, validation_group_keys = split_samples(samples, profile)
    # Freeze the hold-out identity before training. Even if this run errors or
    # a candidate is rejected, the next version evaluates the same SEG groups.
    if validation_group_keys and profile.get("validation_group_keys") != validation_group_keys:
        profile["validation_group_keys"] = validation_group_keys
        write_json(profile_path, profile)
    train_samples, new_train = select_incremental_train(train_all, profile)
    new_train_groups = {sample_group_key(x) for x in new_train}
    if (
        profile.get("active_adapter")
        and len(new_train_groups) < args.min_new_samples
        and len(new_train) < args.min_new_samples
    ):
        raise RuntimeError(
            f"현재 adapter 이후 새 Human-corrected SEG {len(new_train_groups)}개 / "
            f"새 supervised sample {len(new_train)}개입니다. "
            f"둘 중 하나가 최소 {args.min_new_samples}개 필요합니다."
        )
    if len(train_samples) < 2 or len(val_samples) < 1:
        raise RuntimeError("train/validation split에 충분한 데이터가 없습니다")

    processor = AutoProcessor.from_pretrained(args.base_model)
    try:
        processor.tokenizer.set_prefix_tokens(language="korean", task="transcribe")
    except Exception:
        pass

    active_name = str(profile.get("active_adapter") or "").strip()
    active_path = prof_root / "adapters" / active_name if active_name else None
    if active_path and not active_path.is_dir():
        active_path = None

    update_status(
        status_file,
        stage="baseline",
        stage_label="현재 모델 오류율 측정",
        progress=0.06,
        message=f"고정 validation {len(val_samples)}개에서 CER/WER 측정 중",
        train_samples=len(train_samples),
        validation_samples=len(val_samples),
        new_samples=len(new_train),
        new_corrections=len(new_train_groups),
    )

    model = load_model(args.base_model, active_path, trainable=True)
    before_metrics, _, _ = predict_samples(
        model, processor, val_samples,
        status_file=status_file,
        progress_base=0.07,
        progress_span=0.13,
        message="현재 모델 평가",
    )

    if hasattr(model, "gradient_checkpointing_enable"):
        model.gradient_checkpointing_enable()
    if hasattr(model, "enable_input_require_grads"):
        try:
            model.enable_input_require_grads()
        except Exception:
            pass
    model.train()

    ds = SpeechTextDataset(train_samples, processor)
    collator = Collator(processor, int(model.config.decoder_start_token_id))
    loader = DataLoader(ds, batch_size=1, shuffle=True, collate_fn=collator, num_workers=0)
    params = [p for p in model.parameters() if p.requires_grad]
    if not params:
        raise RuntimeError("LoRA trainable parameters were not created")
    optimizer = torch.optim.AdamW(params, lr=args.learning_rate)
    scaler = torch.amp.GradScaler("cuda", enabled=torch.cuda.is_available())
    accumulation = max(1, args.grad_accum)
    planned_steps = min(args.max_steps, max(1, math.ceil(len(loader) * args.epochs / accumulation)))
    optimizer.zero_grad(set_to_none=True)
    global_step = 0
    micro_step = 0
    losses = []

    update_status(
        status_file,
        stage="train",
        stage_label="Professor LoRA 학습",
        progress=0.22,
        message=f"q_proj/v_proj LoRA · rank 8 · 최대 {planned_steps} optimizer steps",
        total_steps=planned_steps,
        current_step=0,
        before=before_metrics,
    )

    def optimizer_step():
        nonlocal global_step
        scaler.unscale_(optimizer)
        torch.nn.utils.clip_grad_norm_(params, 1.0)
        scaler.step(optimizer)
        scaler.update()
        optimizer.zero_grad(set_to_none=True)
        global_step += 1
        frac = global_step / max(1, planned_steps)
        update_status(
            status_file,
            progress=0.22 + 0.53 * min(1.0, frac),
            message=f"LoRA 학습 · step {global_step}/{planned_steps} · loss {np.mean(losses[-20:]):.4f}",
            current_step=global_step,
            loss=float(np.mean(losses[-20:])),
        )

    stop = False
    for epoch in range(args.epochs):
        if stop:
            break
        accumulated_this_epoch = 0
        for batch in loader:
            micro_step += 1
            accumulated_this_epoch += 1
            batch = {k: v.to("cuda:0") if torch.cuda.is_available() else v for k, v in batch.items()}
            with torch.autocast(device_type="cuda", dtype=torch.float16, enabled=torch.cuda.is_available()):
                out = model(**batch)
                loss = out.loss / accumulation
            scaler.scale(loss).backward()
            losses.append(float(loss.detach().cpu()) * accumulation)
            if accumulated_this_epoch < accumulation:
                continue
            optimizer_step()
            accumulated_this_epoch = 0
            if global_step >= planned_steps:
                stop = True
                break

        # Do not discard the last partial accumulation at an epoch boundary.
        if not stop and accumulated_this_epoch:
            optimizer_step()
            if global_step >= planned_steps:
                stop = True

    if global_step == 0:
        raise RuntimeError("LoRA optimizer performed zero steps")

    update_status(
        status_file,
        stage="candidate_eval",
        stage_label="새 Adapter 검증",
        progress=0.77,
        message="같은 hold-out 데이터에서 새 LoRA의 CER/WER를 측정하는 중",
    )
    after_metrics, _, _ = predict_samples(
        model, processor, val_samples,
        status_file=status_file,
        progress_base=0.78,
        progress_span=0.15,
        message="새 Adapter 평가",
    )

    next_version = int(profile.get("adapter_version") or 0) + 1
    name = f"v{next_version:04d}"
    adapters_dir = prof_root / "adapters"
    adapters_dir.mkdir(parents=True, exist_ok=True)
    temp_dir = adapters_dir / (name + ".tmp")
    final_dir = adapters_dir / name
    if temp_dir.exists():
        shutil.rmtree(temp_dir)
    model.save_pretrained(temp_dir)

    improved = after_metrics["cer"] <= before_metrics["cer"] + 1e-12
    history = list(profile.get("history") or [])
    event = {
        "version": name,
        "trained_at": now_iso(),
        "before": before_metrics,
        "after": after_metrics,
        "train_samples": len(train_samples),
        "validation_samples": len(val_samples),
        "new_samples": len(new_train),
        "new_corrections": len(new_train_groups),
        "optimizer_steps": global_step,
        "learning_rate": args.learning_rate,
        "promoted": bool(improved),
    }
    history.append(event)

    if improved:
        if final_dir.exists():
            shutil.rmtree(final_dir)
        temp_dir.replace(final_dir)
        profile.update({
            "professor_id": args.professor_id,
            "active_adapter": name,
            "adapter_version": next_version,
            "metrics": after_metrics,
            "previous_metrics": before_metrics,
            "last_trained_at": event["trained_at"],
            "trained_sample_ids": sorted({str(x.get("id")) for x in train_all}),
            "history": history[-50:],
        })
        write_json(profile_path, profile)
        status = "done"
        stage = "promoted"
        stage_label = "새 Adapter 적용 완료"
        message = f"CER {before_metrics['cer']*100:.2f}% → {after_metrics['cer']*100:.2f}% · {name} 활성화"
    else:
        rejected = prof_root / "rejected" / name
        rejected.parent.mkdir(parents=True, exist_ok=True)
        if rejected.exists():
            shutil.rmtree(rejected)
        temp_dir.replace(rejected)
        profile.update({"history": history[-50:]})
        write_json(profile_path, profile)
        status = "rejected"
        stage = "rejected"
        stage_label = "성능 회귀 · 기존 Adapter 유지"
        message = f"CER {before_metrics['cer']*100:.2f}% → {after_metrics['cer']*100:.2f}% · 자동 승격하지 않음"

    update_status(
        status_file,
        status=status,
        stage=stage,
        stage_label=stage_label,
        progress=1.0,
        message=message,
        before=before_metrics,
        after=after_metrics,
        candidate=name,
        promoted=bool(improved),
        completed_at=now_iso(),
        current_step=global_step,
        total_steps=planned_steps,
    )

    del model
    gc.collect()
    if torch.cuda.is_available():
        torch.cuda.empty_cache()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--professor-id", required=True)
    ap.add_argument("--data-root", default="/workspace/data")
    ap.add_argument("--base-model", default="/workspace/batisay-ko-large")
    ap.add_argument("--status-file", default="")
    ap.add_argument("--epochs", type=int, default=1)
    ap.add_argument("--grad-accum", type=int, default=8)
    ap.add_argument("--max-steps", type=int, default=240)
    ap.add_argument("--learning-rate", type=float, default=1e-4)
    ap.add_argument("--min-samples", type=int, default=12)
    ap.add_argument("--min-new-samples", type=int, default=8)
    args = ap.parse_args()

    status_file = Path(args.status_file) if args.status_file else Path(args.data_root) / "professors" / args.professor_id / "training_status.json"
    try:
        train(args)
    except Exception as exc:
        update_status(
            status_file,
            status="error",
            stage="error",
            stage_label="학습 실패",
            progress=1.0,
            message="Professor LoRA 학습 중 오류가 발생했습니다",
            error=repr(exc),
            completed_at=now_iso(),
        )
        raise


if __name__ == "__main__":
    main()
